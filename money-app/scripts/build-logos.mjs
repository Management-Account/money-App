// Scans logos/ and rewrites js/logos.js. A file named <institution id>.(png|svg|webp|jpg) is used as that bank's logo.
// Run:  node scripts/build-logos.mjs      (ids are listed in js/institutions.js, e.g. nbe.png, cib.svg, vfcash.png)
import { readdirSync, writeFileSync } from 'node:fs';
import { INSTITUTIONS } from '../js/institutions.js';

const ids = new Set(INSTITUTIONS.map((i) => i.id));
const files = readdirSync(new URL('../logos/', import.meta.url)).filter((f) => /\.(png|svg|webp|jpe?g)$/i.test(f)).sort();
const map = {};
const unknown = [];
for (const f of files) {
  const id = f.replace(/\.[^.]+$/, '');
  if (ids.has(id)) map[id] = `logos/${f}`;
  else unknown.push(f);
}
const body = Object.entries(map).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
writeFileSync(new URL('../js/logos.js', import.meta.url), `// Generated by scripts/build-logos.mjs from the files in logos/. Edit by adding files, then re-run it.
// Official logos are trademarks and are not bundled; add only logos you have the right to use.
export const LOGOS = {
${body}
};
`);
console.log(`${Object.keys(map).length} logos linked.` + (unknown.length ? ` Ignored (name is not an institution id): ${unknown.join(', ')}` : ''));
console.log('Institution ids:', [...ids].join(' '));
